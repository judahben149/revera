package com.jj.revera.buildlogic

import org.gradle.api.DefaultTask
import org.gradle.api.Plugin
import org.gradle.api.Project
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.MapProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction
import org.gradle.kotlin.dsl.configure
import org.gradle.kotlin.dsl.register
import org.jetbrains.kotlin.gradle.dsl.KotlinMultiplatformExtension

/**
 * `revera.build.config` — generates a multiplatform `BuildConfig` object in commonMain from
 * gradle.properties, so every platform reads the same version/environment values.
 * Override at build time with `-Prevera.environment=prod` etc.
 */
class BuildConfigConventionPlugin : Plugin<Project> {
    override fun apply(target: Project) =
        with(target) {
            val generate =
                tasks.register<GenerateBuildConfigTask>("generateReveraBuildConfig") {
                    packageName.set(reveraNamespace)
                    fields.put("APP_NAME", "Revera")
                    fields.put("APPLICATION_ID", BASE_PACKAGE)
                    fields.put("VERSION_NAME", stringProperty("revera.versionName", "1.0.0"))
                    fields.put("VERSION_CODE", stringProperty("revera.versionCode", "1"))
                    fields.put("ENVIRONMENT", stringProperty("revera.environment", "dev"))
                    fields.put("API_BASE_URL", stringProperty("revera.apiBaseUrl", ""))
                    outputDirectory.set(layout.buildDirectory.dir("generated/revera/buildConfig/commonMain/kotlin"))
                }

            extensions.configure<KotlinMultiplatformExtension> {
                sourceSets.commonMain {
                    kotlin.srcDir(generate.flatMap(GenerateBuildConfigTask::outputDirectory))
                }
            }
        }
}

@CacheableTask
abstract class GenerateBuildConfigTask : DefaultTask() {
    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val fields: MapProperty<String, String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val pkg = packageName.get()
        val body =
            fields.get().entries.joinToString(separator = "\n") { (name, value) ->
                val escaped = value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
                "    const val $name: String = \"$escaped\""
            }
        val file =
            outputDirectory
                .get()
                .asFile
                .resolve(pkg.replace('.', '/'))
                .resolve("BuildConfig.kt")
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by revera.build.config — do not edit. Values come from gradle.properties.
            |package $pkg
            |
            |public object BuildConfig {
            |$body
            |}
            |
            """.trimMargin(),
        )
    }
}
